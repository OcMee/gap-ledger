"""Build app/zips.js: Orange County ZIP codes with an approximate center point and city name.

Sources:
  - ZIP centers and city names: the `zipcodes` npm package 8.0.0 (BSD license), built from the free zipcode database.
    These are approximate center points, not ZIP boundaries.
  - Orange County boundary: US Census Bureau cartographic boundaries via the `us-atlas` npm package 3.0.1 (ISC license).
A ZIP is kept when its center point falls inside the Orange County boundary.

Usage:
  npm pack zipcodes@8.0.0 us-atlas@3.0.1, unpack each, then
  python3 -I -c "import json;s=open('zipcodes/lib/codes.js').read();o=json.JSONDecoder().raw_decode(s[len('exports.codes = '):])[0];json.dump([v for v in o.values() if v.get('state')=='CA'],open('ca.json','w'))"
  (reads the package's data file as JSON; does not run the package's code)
  python3 tools/build_zips.py ca.json path/to/us-atlas/counties-10m.json
"""
import json, pathlib, sys

CA = json.loads(pathlib.Path(sys.argv[1]).read_text())
topo = json.loads(pathlib.Path(sys.argv[2]).read_text())
OUT = pathlib.Path(__file__).resolve().parent.parent / "app" / "zips.js"

sc, tr = topo["transform"]["scale"], topo["transform"]["translate"]


def decode(arc):
    x = y = 0
    pts = []
    for dx, dy in arc:
        x += dx; y += dy
        pts.append((x * sc[0] + tr[0], y * sc[1] + tr[1]))
    return pts


ARCS = [decode(a) for a in topo["arcs"]]


def ring(idx):
    pts = []
    for i in idx:
        a = ARCS[i] if i >= 0 else ARCS[~i][::-1]
        pts.extend(a if not pts else a[1:])
    return pts


oc = next(g for g in topo["objects"]["counties"]["geometries"] if g["id"] == "06059")
polys = [oc["arcs"]] if oc["type"] == "Polygon" else oc["arcs"]
rings = [ring(r) for poly in polys for r in poly]  # outer rings and holes; even-odd rule handles both


def inside(lng, lat):
    hit = False
    for pts in rings:
        j = len(pts) - 1
        for i in range(len(pts)):
            xi, yi = pts[i]; xj, yj = pts[j]
            if (yi > lat) != (yj > lat) and lng < (xj - xi) * (lat - yi) / (yj - yi) + xi:
                hit = not hit
            j = i
    return hit


zips = {}
for z in CA:
    lat, lng = z.get("latitude"), z.get("longitude")
    if lat is None or lng is None:
        continue
    if inside(float(lng), float(lat)):
        zips[z["zip"]] = [round(float(lat), 4), round(float(lng), 4), z["city"].title()]

zips = dict(sorted(zips.items()))
OUT.write_text("// Generated by tools/build_zips.py. Orange County ZIP codes: [lat, lng, city]. Approximate ZIP center points\n"
               "// from the zipcodes npm package (BSD), kept when inside the US Census Orange County boundary. Do not edit by hand.\n"
               "window.OC_ZIPS = " + json.dumps(zips, separators=(",", ":")) + ";\n")
print(f"wrote {OUT.name}: {len(zips)} ZIP codes, {OUT.stat().st_size // 1024} KB")
