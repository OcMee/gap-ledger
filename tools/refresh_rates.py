"""Refresh the mortgage rate series used by the app.

Source: Freddie Mac Primary Mortgage Market Survey, 30-year fixed, weekly,
via FRED series MORTGAGE30US. Writes app/rates.js.
Usage: python3 tools/refresh_rates.py
"""
import csv, io, json, pathlib, urllib.request, datetime

URL = "https://fred.stlouisfed.org/graph/fredgraph.csv?id=MORTGAGE30US"
OUT = pathlib.Path(__file__).resolve().parent.parent / "app" / "rates.js"

raw = urllib.request.urlopen(URL, timeout=30).read().decode()
rows = [(d, float(v)) for d, v in list(csv.reader(io.StringIO(raw)))[1:] if v not in (".", "")]
rows = [r for r in rows if r[0] >= "2000-01-01"]
data = {
    "series": "MORTGAGE30US",
    "name": "Freddie Mac 30-Year Fixed Rate Mortgage Average (PMMS), weekly",
    "url": "https://fred.stlouisfed.org/series/MORTGAGE30US",
    "fetched": datetime.date.today().isoformat(),
    "points": rows,
}
OUT.write_text("// Generated by tools/refresh_rates.py. Do not edit by hand.\nwindow.RATES = "
               + json.dumps(data, separators=(",", ":")) + ";\n")
print(f"wrote {OUT} with {len(rows)} weeks, latest {rows[-1]}")
