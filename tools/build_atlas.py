"""Build app/atlas.js: county outlines for the atlas-style Map tab.

The map opens on the Orange County frame (VIEW), and can zoom out to a wider WORLD that reaches about
50 miles past the county line, so a 50-mile ZIP search circle fits. Pixel scale is the same in both.

Source: US Census Bureau cartographic boundaries via the us-atlas npm package (counties-10m.json, ISC license; data public domain).
Usage: python3 tools/build_atlas.py path/to/counties-10m.json
Projection: equirectangular with longitude scaled by cos(33.7 deg), the same math map.js uses for pins.
"""
import json, math, pathlib, sys

SRC = pathlib.Path(sys.argv[1])
OUT = pathlib.Path(__file__).resolve().parent.parent / "app" / "atlas.js"
# VIEW: the default Orange County frame (unchanged from the first atlas). WORLD: the zoomed-out extent.
VLNG0, VLNG1, VLAT0, VLAT1, VH = -118.22, -117.33, 33.36, 34.00, 720
LNG0, LNG1, LAT0, LAT1 = -119.05, -116.45, 32.65, 34.72
K = math.cos(math.radians(33.7))
S = VH / (VLAT1 - VLAT0)
VW = round((VLNG1 - VLNG0) * K * S)
W = round((LNG1 - LNG0) * K * S)
H = round((LAT1 - LAT0) * S)
COUNTIES = {"oc": "06059", "la": "06037", "riv": "06065", "sb": "06071", "sd": "06073", "ven": "06111", "imp": "06025", "kern": "06029"}

topo = json.loads(SRC.read_text())
sc, tr = topo["transform"]["scale"], topo["transform"]["translate"]


def decode_arc(arc):
    x = y = 0
    pts = []
    for dx, dy in arc:
        x += dx; y += dy
        pts.append((x * sc[0] + tr[0], y * sc[1] + tr[1]))
    return pts


ARCS = [decode_arc(a) for a in topo["arcs"]]


def ring(idx_list):
    pts = []
    for i in idx_list:
        a = ARCS[i] if i >= 0 else ARCS[~i][::-1]
        pts.extend(a if not pts else a[1:])
    return pts


def polygons(geom):
    if geom["type"] == "Polygon":
        return [geom["arcs"]]
    if geom["type"] == "MultiPolygon":
        return geom["arcs"]
    return []


def smooth(pts):
    """Closed Catmull-Rom curve through the points, as cubic Bezier segments (softens a coarse outline)."""
    n = len(pts)
    d = [f"M{pts[0][0]:.1f} {pts[0][1]:.1f}"]
    for i in range(n):
        p0, p1, p2, p3 = pts[i - 1], pts[i], pts[(i + 1) % n], pts[(i + 2) % n]
        c1 = (p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6)
        c2 = (p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6)
        d.append(f"C{c1[0]:.1f} {c1[1]:.1f} {c2[0]:.1f} {c2[1]:.1f} {p2[0]:.1f} {p2[1]:.1f}")
    return "".join(d) + "Z"


def to_path(geom, proj, pad=60, w=W, h=H):
    out = []
    for poly in polygons(geom):
        for r in poly:
            pts = [proj(lng, lat) for lng, lat in ring(r)]
            # Clamp far-away points: the map clips to its frame, and this keeps the file small.
            pts = [(min(max(x, -pad), w + pad), min(max(y, -pad), h + pad)) for x, y in pts]
            simp = [pts[0]]
            for p in pts[1:]:
                if abs(p[0] - simp[-1][0]) + abs(p[1] - simp[-1][1]) >= 0.6:
                    simp.append(p)
            if len(simp) > 2:
                out.append(smooth(simp))
    return "".join(out)


main = lambda lng, lat: ((lng - LNG0) * K * S, (LAT1 - lat) * S)
geoms = {g["id"]: g for g in topo["objects"]["counties"]["geometries"]}
counties = {k: to_path(geoms[f], main) for k, f in COUNTIES.items() if f in geoms}

# Inset: all California counties merged visually (drawn as county shapes with no inner strokes), OC highlighted.
IW, IH = 150, 172
ca = [g for g in topo["objects"]["counties"]["geometries"] if str(g["id"]).startswith("06")]
ilng0, ilng1, ilat0, ilat1 = -124.6, -114.0, 32.4, 42.1
ik = math.cos(math.radians(37.2))
iscale = min(IW / ((ilng1 - ilng0) * ik), IH / (ilat1 - ilat0))
inset = lambda lng, lat: ((lng - ilng0) * ik * iscale, (ilat1 - lat) * iscale)
inset_ca = "".join(to_path(g, inset, pad=5, w=IW, h=IH) for g in ca)
inset_oc = to_path(geoms["06059"], inset, pad=5, w=IW, h=IH)

view = {"w": VW, "h": VH, "cx": round(main(VLNG0, VLAT1)[0] + VW / 2, 1), "cy": round(main(VLNG0, VLAT1)[1] + VH / 2, 1)}
data = {"src": "US Census Bureau cartographic boundaries (us-atlas counties-10m)", "lng0": LNG0, "lng1": LNG1, "lat0": LAT0, "lat1": LAT1,
        "H": H, "W": W, "k": K, "s": S, "view": view, "counties": counties, "inset": {"w": IW, "h": IH, "ca": inset_ca, "oc": inset_oc}}
OUT.write_text("// Generated by tools/build_atlas.py from US Census county boundaries. Do not edit by hand.\nwindow.ATLAS = "
               + json.dumps(data, separators=(",", ":")) + ";\n")
print(f"wrote {OUT.name}: {OUT.stat().st_size // 1024} KB, world {W}x{H}, view {VW}x{VH}, {S:.1f} px per degree of latitude")
